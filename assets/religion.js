// 세계역사(WH_SCALE)와 달리 기원전 2000년부터 시작한다. 종교는 그 이전 자료가 거의 없다.
const REL_SCALE = [
  [-2000, 0], [-1000, 80], [-500, 150], [0, 230], [500, 320], [1000, 410],
  [1300, 490], [1500, 560], [1700, 640], [1800, 700], [1900, 770], [1950, 850], [2030, 940],
];
function relY(year){
  const S = REL_SCALE;
  if (year <= S[0][0]) return S[0][1];
  if (year >= S[S.length-1][0]) return S[S.length-1][1];
  for (let i=0; i<S.length-1; i++){
    const [y0,p0] = S[i], [y1,p1] = S[i+1];
    if (year >= y0 && year <= y1) return p0 + (p1-p0) * (year-y0) / (y1-y0);
  }
  return 0;
}
