// ── 시간축 앵커 ──
// 선형으로 그리면 5000년 중 최근 100년이 2px 가 된다. 시대마다 배율을 달리해
// '같은 높이 = 같은 시대'는 지키면서 근현대도 읽히게 만든다.
// 시작을 기원전 3200년으로 둔 이유: 이집트 고왕국(약 기원전 2686)과 피라미드 시대가
// 축 밖으로 밀려나기 때문이다. 동아시아만 보면 기원전 2500이면 충분하지만,
// 축은 모든 섹션이 공유해야 '같은 높이 = 같은 시대'가 성립한다.
const WH_SCALE = [
  [-3200, 0], [-2500, 45], [-1000, 135], [-500, 205], [0, 285], [500, 375], [1000, 465],
  [1300, 545], [1500, 615], [1700, 695], [1800, 755], [1900, 825], [1950, 905], [2030, 995],
];
function whY(year){
  const S = WH_SCALE;
  if (year <= S[0][0]) return S[0][1];
  if (year >= S[S.length-1][0]) return S[S.length-1][1];
  for (let i=0; i<S.length-1; i++){
    const [y0,p0] = S[i], [y1,p1] = S[i+1];
    if (year >= y0 && year <= y1) return p0 + (p1-p0) * (year-y0) / (y1-y0);
  }
  return 0;
}
